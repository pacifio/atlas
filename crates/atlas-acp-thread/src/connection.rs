/// A login command an agent's own CLI must run in a terminal.
///
/// Zed returns `task::SpawnInTerminal` here and hands it to its terminal task
/// system (`build_terminal_auth_task`, `connection.rs:69-89`). Atlas has no such
/// task type, so the port keeps the same *fields* and lets the host decide how
/// to run it — Atlas already streams a login CLI's output into `AgentOAuthModal`.
/// Zed's `use_new_terminal` / `allow_concurrent_runs` / `hide: Always` are all
/// consequences of running inside its terminal panel and have no meaning here.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TerminalAuthCommand {
    pub id: String,
    pub label: String,
    pub command: String,
    pub args: Vec<String>,
    /// The full environment to SPAWN this login with — the agent's own, so the
    /// login reaches the network the way the agent does. Inherited variables
    /// included, which for Atlas means the user's whole environment plus the
    /// BYOK keys read out of the keychain.
    ///
    /// Never show this to anyone. It is what a subprocess gets, not what a
    /// human should see: rendered into a shell line it would put the user's
    /// API keys on screen, on the clipboard, and in `~/.zsh_history`.
    pub env: Vec<(String, String)>,
    /// Only what the AGENT declared for this login — its `terminal.env`, or the
    /// `_meta` spec's `env`. Safe to display, and the only part a user running
    /// the command themselves actually needs: their own shell already carries
    /// the rest.
    pub declared_env: Vec<(String, String)>,
}

/// Ported from `build_terminal_auth_task` (`connection.rs:69-89`).
pub fn build_terminal_auth_command(
    id: String,
    label: String,
    command: String,
    args: Vec<String>,
    env: Vec<(String, String)>,
    declared_env: Vec<(String, String)>,
) -> TerminalAuthCommand {
    TerminalAuthCommand {
        id,
        label,
        command,
        args,
        declared_env,
        env,
    }
}

/// A live connection to one agent.
///
/// Deviations from Zed, all mechanical:
/// - `Rc<Self>` → `Arc<Self>`: handlers run on tokio worker threads, so every
///   trait object here is `Send + Sync`. Zed can use `Rc` because everything
///   lives on its foreground thread.
/// - `Task<Result<T>>` → `BoxFuture<'static, Result<T>>`. Zed's `Task` is a
///   GPUI-scheduled future; boxing is the dyn-safe equivalent.
/// - Every `cx: &mut App` / `cx: &App` parameter is gone.
/// - `Entity<AcpThread>` → [`AcpThreadHandle`].
/// - `project: Entity<Project>` is gone; `work_dirs` carries what the port
///   actually needs. Atlas serves `fs/*` from disk (§D12-6), so there is no
///   project buffer store to pass.
pub trait AgentConnection: Send + Sync {
    fn agent_id(&self) -> AgentId;

    fn telemetry_id(&self) -> Arc<str>;

    fn agent_version(&self) -> Option<Arc<str>> {
        None
    }

    fn new_session(
        self: Arc<Self>,
        work_dirs: Vec<PathBuf>,
    ) -> BoxFuture<'static, Result<AcpThreadHandle>>;

    /// Whether this agent supports loading existing sessions.
    fn supports_load_session(&self) -> bool {
        false
    }

    /// Load an existing session by ID.
    fn load_session(
        self: Arc<Self>,
        _session_id: acp::SessionId,
        _work_dirs: Vec<PathBuf>,
        _title: Option<Arc<str>>,
    ) -> BoxFuture<'static, Result<AcpThreadHandle>> {
        Box::pin(async { Err(anyhow::Error::msg("Loading sessions is not supported")) })
    }

    /// Whether this agent supports closing existing sessions.
    fn supports_close_session(&self) -> bool {
        false
    }

    /// Close an existing session. Allows the agent to free the session from memory.
    fn close_session(self: Arc<Self>, _session_id: acp::SessionId) -> BoxFuture<'static, Result<()>> {
        Box::pin(async { Err(anyhow::Error::msg("Closing sessions is not supported")) })
    }

    /// Whether this agent supports resuming existing sessions without loading history.
    fn supports_resume_session(&self) -> bool {
        false
    }

    /// Resume an existing session by ID without replaying previous messages.
    fn resume_session(
        self: Arc<Self>,
        _session_id: acp::SessionId,
        _work_dirs: Vec<PathBuf>,
        _title: Option<Arc<str>>,
    ) -> BoxFuture<'static, Result<AcpThreadHandle>> {
        Box::pin(async { Err(anyhow::Error::msg("Resuming sessions is not supported")) })
    }

    /// Whether this agent supports showing session history.
    fn supports_session_history(&self) -> bool {
        self.supports_load_session() || self.supports_resume_session()
    }

    /// Whether this agent supports additional session directories.
    fn supports_session_additional_directories(&self) -> bool {
        false
    }

    fn auth_methods(&self) -> &[acp::AuthMethod];

    fn terminal_auth_command(
        &self,
        _method: &acp::AuthMethodId,
    ) -> Option<BoxFuture<'static, Result<TerminalAuthCommand>>> {
        None
    }

    fn authenticate(&self, method: acp::AuthMethodId) -> BoxFuture<'static, Result<()>>;

    fn supports_logout(&self) -> bool {
        false
    }

    fn logout(&self) -> BoxFuture<'static, Result<()>> {
        Box::pin(async { Err(anyhow::Error::msg("Logout is not supported")) })
    }

    /// Returns a capability for agents that accept client-generated user message IDs.
    fn client_user_message_ids(&self) -> Option<Arc<dyn AgentSessionClientUserMessageIds>> {
        None
    }

    fn prompt(
        &self,
        params: acp::PromptRequest,
    ) -> BoxFuture<'static, Result<acp::PromptResponse>>;

    fn retry(&self, _session_id: &acp::SessionId) -> Option<Arc<dyn AgentSessionRetry>> {
        None
    }

    fn cancel(&self, session_id: &acp::SessionId);

    /// Request-scoped elicitations are connection-level because they can arrive
    /// before a session thread exists. Session-scoped elicitations stay in the
    /// thread timeline, but use [`crate::ElicitationStore`] for shared processing.
    fn request_elicitations(&self) -> Option<ElicitationStoreHandle> {
        None
    }

    fn truncate(&self, _session_id: &acp::SessionId) -> Option<Arc<dyn AgentSessionTruncate>> {
        None
    }

    fn set_title(&self, _session_id: &acp::SessionId) -> Option<Arc<dyn AgentSessionSetTitle>> {
        None
    }

    /// Returns this agent as an [`AgentModelSelector`] if the model selection
    /// capability is supported, else [`None`].
    fn model_selector(&self, _session_id: &acp::SessionId) -> Option<Arc<dyn AgentModelSelector>> {
        None
    }

    fn telemetry(&self) -> Option<Arc<dyn AgentTelemetry>> {
        None
    }

    fn session_modes(&self, _session_id: &acp::SessionId) -> Option<Arc<dyn AgentSessionModes>> {
        None
    }

    fn session_config_options(
        &self,
        _session_id: &acp::SessionId,
    ) -> Option<Arc<dyn AgentSessionConfigOptions>> {
        None
    }

    fn session_list(&self) -> Option<Arc<dyn AgentSessionList>> {
        None
    }

    fn into_any(self: Arc<Self>) -> Arc<dyn Any + Send + Sync>;
}

impl dyn AgentConnection {
    pub fn downcast<T: 'static + AgentConnection + Sized>(self: Arc<Self>) -> Option<Arc<T>> {
        self.into_any().downcast().ok()
    }
}

