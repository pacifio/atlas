//! The risk map: every changed file, tagged, with its floor flag and the
//! reason it was skipped if it was, in the order a reviewer should read them.
//!
//! Atlas builds this from git itself; no agent writes any of it. Files that
//! are not scanned stay in the map with their reason, so nothing a commit
//! changed silently disappears from the report.

use serde::{Deserialize, Serialize};

use crate::diff::{FileChange, FileStatus};
use crate::tags::{
    adds_install_script, file_name, hunk_tags, is_floor, language_of, path_tags, Language, Tag,
};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum SkipReason {
    Binary,
    TooLarge { added_lines: usize },
    Generated,
    DeletedFile,
    TimeBudget,
    UnsupportedLockfile,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Limits {
    pub max_added_lines_per_file: usize,
    pub max_files: usize,
}

impl Default for Limits {
    fn default() -> Self {
        Self {
            max_added_lines_per_file: 4000,
            max_files: 300,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MappedFile {
    pub change: FileChange,
    pub language: Language,
    /// Path tags and every hunk's tags, without duplicates.
    pub tags: Vec<Tag>,
    /// One entry per hunk, in hunk order.
    pub hunk_tags: Vec<Vec<Tag>>,
    pub floor: bool,
    pub skip: Option<SkipReason>,
}

impl MappedFile {
    pub fn added_count(&self) -> usize {
        self.change.added_lines().count()
    }

    fn weight(&self) -> u32 {
        self.tags.iter().map(|t| t.weight()).sum()
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RiskMap {
    pub files: Vec<MappedFile>,
}

pub fn build(changes: Vec<FileChange>, limits: &Limits) -> RiskMap {
    let mut files: Vec<MappedFile> = changes.into_iter().map(|c| map_file(c, limits)).collect();
    files.sort_by(|a, b| {
        b.floor
            .cmp(&a.floor)
            .then(b.weight().cmp(&a.weight()))
            .then(b.added_count().cmp(&a.added_count()))
            .then(a.change.path.cmp(&b.change.path))
    });
    for file in files.iter_mut().skip(limits.max_files) {
        if file.skip.is_none() {
            file.skip = Some(SkipReason::TooLarge {
                added_lines: file.added_count(),
            });
        }
    }
    RiskMap { files }
}

fn map_file(change: FileChange, limits: &Limits) -> MappedFile {
    let language = language_of(&change.path);
    let mut tags = path_tags(&change.path);
    let is_package_json = file_name(&change.path) == "package.json";
    let hunk_tags: Vec<Vec<Tag>> = change
        .hunks
        .iter()
        .map(|h| {
            let mut t = hunk_tags(language, h);
            if is_package_json && adds_install_script(h) {
                t.push(Tag::InstallScript);
            }
            t
        })
        .collect();
    for tag in hunk_tags.iter().flatten() {
        if !tags.contains(tag) {
            tags.push(*tag);
        }
    }
    let floor = tags.iter().any(|t| is_floor(*t));
    let added = change.added_lines().count();
    let skip = if change.binary {
        Some(SkipReason::Binary)
    } else if change.status == FileStatus::Deleted {
        Some(SkipReason::DeletedFile)
    } else if is_generated(&change) {
        Some(SkipReason::Generated)
    } else if added > limits.max_added_lines_per_file {
        Some(SkipReason::TooLarge { added_lines: added })
    } else {
        None
    };
    MappedFile {
        change,
        language,
        tags,
        hunk_tags,
        floor,
        skip,
    }
}

/// Generated by path alone: minified bundles, source maps, and build output
/// folders at the top of the repository or of a workspace package. A header
/// is checked by the pipeline against the file as it was before the commit,
/// so text an agent adds can never mark its own file generated.
fn is_generated(change: &FileChange) -> bool {
    let name = file_name(&change.path);
    if name.ends_with(".min.js") || name.ends_with(".min.css") || name.ends_with(".map") {
        return true;
    }
    let segments: Vec<&str> = change.path.split('/').collect();
    let build_dir = |s: &str| matches!(s, "dist" | "build" | "out" | ".next" | "target");
    let workspace = |s: &str| matches!(s, "packages" | "apps" | "crates" | "libs");
    match segments.as_slice() {
        [first, _, ..] if build_dir(first) => true,
        [first, _pkg, dir, _, ..] if workspace(first) && build_dir(dir) => true,
        _ => false,
    }
}
