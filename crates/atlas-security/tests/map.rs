use atlas_security::diff::parse_unified;
use atlas_security::map::{build, Limits, SkipReason};
use atlas_security::tags::{language_of, Language, Tag};

/// A one-file diff adding `lines` to `path`.
fn file_diff(path: &str, lines: &[&str]) -> String {
    let mut s = format!(
        "diff --git a/{path} b/{path}\n--- a/{path}\n+++ b/{path}\n@@ -1,0 +1,{} @@\n",
        lines.len()
    );
    for l in lines {
        s.push('+');
        s.push_str(l);
        s.push('\n');
    }
    s
}

fn map_of(diff: &str) -> atlas_security::map::RiskMap {
    build(parse_unified(diff.as_bytes()), &Limits::default())
}

#[test]
fn language_by_extension() {
    assert_eq!(language_of("src/a.tsx"), Language::JsTs);
    assert_eq!(language_of("b.rs"), Language::Rust);
    assert_eq!(language_of("pkg/c.py"), Language::Python);
    assert_eq!(language_of("main.go"), Language::Other);
}

#[test]
fn workflow_and_lockfile_are_floors() {
    let diff =
        file_diff(".github/workflows/ci.yml", &["on: push"]) + &file_diff("Cargo.lock", &["x"]);
    let map = map_of(&diff);
    assert!(
        map.files.iter().all(|f| f.floor),
        "{:?}",
        map.files
            .iter()
            .map(|f| (&f.change.path, f.floor))
            .collect::<Vec<_>>()
    );
    let workflow = map
        .files
        .iter()
        .find(|f| f.change.path.ends_with("ci.yml"))
        .unwrap();
    assert!(workflow.tags.contains(&Tag::CiWorkflow));
}

#[test]
fn floor_files_sort_first() {
    let diff = file_diff("src/a.rs", &["let x = 1;"])
        + &file_diff("src/b.rs", &["Command::new(\"git\");"])
        + &file_diff("Cargo.lock", &["version = \"1\""]);
    let order: Vec<_> = map_of(&diff)
        .files
        .into_iter()
        .map(|f| f.change.path)
        .collect();
    assert_eq!(order, vec!["Cargo.lock", "src/b.rs", "src/a.rs"]);
}

#[test]
fn tauri_command_tagged_entry_point() {
    let map = map_of(&file_diff(
        "src-tauri/src/commands/x.rs",
        &["#[tauri::command]", "pub fn x() {}"],
    ));
    assert!(map.files[0].hunk_tags[0].contains(&Tag::EntryPoint));
    assert!(map.files[0].tags.contains(&Tag::EntryPoint));
}

#[test]
fn python_shell_true_tagged() {
    let map = map_of(&file_diff("tool.py", &["subprocess.run(cmd, shell=True)"]));
    assert!(map.files[0].tags.contains(&Tag::ShellSink));
}

#[test]
fn removed_lines_do_not_tag() {
    let diff =
        "diff --git a/a.js b/a.js\n--- a/a.js\n+++ b/a.js\n@@ -1,2 +1,1 @@\n keep()\n-eval(x)\n";
    let map = map_of(diff);
    assert!(!map.files[0].tags.contains(&Tag::EvalSink));
}

#[test]
fn minified_file_skipped_as_generated() {
    let map = map_of(&file_diff("public/app.min.js", &["var a=1"]));
    assert_eq!(map.files[0].skip, Some(SkipReason::Generated));
}

#[test]
fn an_added_generated_header_does_not_mark_the_file_generated() {
    // Text the commit adds is not trusted to switch the scan off; the
    // pipeline checks the header the file had before the commit instead.
    let map = map_of(&file_diff(
        "src/gen.rs",
        &["// @generated by build.rs", "pub const X: u8 = 1;"],
    ));
    assert_eq!(map.files[0].skip, None);
}

#[test]
fn only_top_level_build_folders_are_generated() {
    assert_eq!(
        map_of(&file_diff("dist/app.js", &["x"])).files[0].skip,
        Some(SkipReason::Generated)
    );
    assert_eq!(
        map_of(&file_diff("packages/ui/dist/i.js", &["x"])).files[0].skip,
        Some(SkipReason::Generated)
    );
    assert_eq!(
        map_of(&file_diff("src/build/client.ts", &["x"])).files[0].skip,
        None
    );
    assert_eq!(
        map_of(&file_diff("src/features/out/x.ts", &["x"])).files[0].skip,
        None
    );
}

#[test]
fn huge_file_skipped_too_large() {
    let lines: Vec<String> = (0..5000).map(|i| format!("let v{i} = {i};")).collect();
    let refs: Vec<&str> = lines.iter().map(String::as_str).collect();
    let map = map_of(&file_diff("src/big.rs", &refs));
    assert_eq!(
        map.files[0].skip,
        Some(SkipReason::TooLarge { added_lines: 5000 })
    );
}

#[test]
fn deleted_file_skipped() {
    let diff = "diff --git a/old.rs b/old.rs\ndeleted file mode 100644\n--- a/old.rs\n+++ /dev/null\n@@ -1 +0,0 @@\n-fn a() {}\n";
    let map = map_of(diff);
    assert_eq!(map.files[0].skip, Some(SkipReason::DeletedFile));
}

#[test]
fn files_beyond_max_files_are_skipped_but_floors_kept() {
    let mut diff = file_diff("Cargo.lock", &["x"]);
    for i in 0..5 {
        diff += &file_diff(&format!("src/f{i}.rs"), &["let a = 1;"]);
    }
    let map = build(
        parse_unified(diff.as_bytes()),
        &Limits {
            max_added_lines_per_file: 4000,
            max_files: 3,
        },
    );
    let skipped = map
        .files
        .iter()
        .filter(|f| matches!(f.skip, Some(SkipReason::TooLarge { .. })))
        .count();
    assert_eq!(skipped, 3);
    assert!(map.files[0].floor && map.files[0].skip.is_none());
}

#[test]
fn agent_config_paths_are_floors() {
    for path in [
        ".mcp.json",
        "AGENTS.md",
        "CLAUDE.md",
        ".claude/settings.json",
        ".cursor/rules.md",
        "skills/x/SKILL.md",
    ] {
        let map = map_of(&file_diff(path, &["x"]));
        assert!(map.files[0].tags.contains(&Tag::AgentConfig), "{path}");
        assert!(map.files[0].floor, "{path}");
    }
}

#[test]
fn react_hooks_dir_is_not_agent_config() {
    let map = map_of(&file_diff(
        "src/hooks/use-thing.ts",
        &["export const x = 1;"],
    ));
    assert!(!map.files[0].tags.contains(&Tag::AgentConfig));
    assert!(!map.files[0].floor);
    let husky = map_of(&file_diff(".husky/pre-commit", &["bun test"]));
    assert!(husky.files[0].tags.contains(&Tag::AgentConfig));
}

#[test]
fn test_paths_are_recognised() {
    use atlas_security::tags::is_test_path;
    for p in [
        "crates/x/tests/scan.rs",
        "src/components/toast-icons.test.tsx",
        "src/a.spec.ts",
        "pkg/__tests__/a.js",
        "app/test_views.py",
        "app/views_test.py",
        "conftest.py",
        "src/lib_test.rs",
        "eval/fixtures/a.json",
    ] {
        assert!(is_test_path(p), "{p}");
    }
    for p in [
        "src/testing-library.ts",
        "src/contest.rs",
        "src/latest.py",
        "docs/attest.md",
    ] {
        assert!(!is_test_path(p), "{p}");
    }
}
