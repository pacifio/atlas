/** Flat search across every category. Empty query returns nothing — the caller
 *  shows the categories instead. */
export function searchEmoji(query: string, limit = 60): EmojiEntry[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const out: EmojiEntry[] = [];
  for (const cat of EMOJI_CATEGORIES) {
    for (const entry of cat.emoji) {
      if (entry.keywords.includes(q)) {
        out.push(entry);
        if (out.length >= limit) return out;
      }
    }
  }
  return out;
}
