// Deliberately inline rather than a dependency: the full Unicode set with
// keywords is multiple megabytes, which is real weight in a desktop bundle for
// a feature that is "insert a smiley into a chat message". This covers the
// common vocabulary of a work chat, and swapping in a full dataset later is
// contained to this one module — nothing else imports the shape.
//
// Reactions are a different thing entirely: those are constrained to the
// server's `CHAT_REACTION_EMOJI` allowlist because a `react` outside it is a
// 400. Message text has no such limit, which is why this list can be broader.

